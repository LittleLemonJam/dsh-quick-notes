/**
 * Build the Client bundle.
 *
 * The DSH Web module loader expects a single script that registers a lazy
 * factory under the package name:
 *
 *   window.__ModuleLoader__.load({ id, factory(require) { ... } })
 *
 * Source lives in `src/client/` as ordinary ESM modules; esbuild bundles them
 * into one CommonJS body, and this script wraps that body in the loader
 * factory. React is the only external: it comes from the host module table.
 *
 * Usage:
 *   node scripts/build.mjs           write ./client.js
 *   node scripts/build.mjs --check   fail when ./client.js is out of date
 */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { build } from 'esbuild'

const PACKAGE_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = join(PACKAGE_ROOT, 'src', 'client', 'index.js')
const OUTPUT = join(PACKAGE_ROOT, 'client.js')
const PACKAGE_NAME = 'dsh-quick-notes'
const CHECK = process.argv.includes('--check')

/** The version shown by the settings panel. */
const VERSION = JSON.parse(await readFile(join(PACKAGE_ROOT, 'package.json'), 'utf8')).version

/** Header comment of the generated artifact. */
const HEADER = `/**
 * ${PACKAGE_NAME} — Client bundle.
 *
 * Generated by scripts/build.mjs from src/client/index.js.
 * Do not edit this file by hand: run \`npm run build\` instead.
 */`

/** Open the loader factory around the CommonJS body. */
const BANNER = `${HEADER}
window.__ModuleLoader__.load({
  id: '${PACKAGE_NAME}',
  factory(require) {
    const module = { exports: {} }
    const exports = module.exports
`

/** Close the loader factory and return the plugin object. */
const FOOTER = `
    const plugin = module.exports.createPlugin()
    if (plugin === null || typeof plugin !== 'object') {
      throw new Error('${PACKAGE_NAME}: client entry must export createPlugin()')
    }
    return plugin
  },
})
`

/**
 * Bundle the Client entry into the loader script.
 * @returns the generated file text.
 */
async function bundle() {
  const result = await build({
    entryPoints: [ENTRY],
    absWorkingDir: PACKAGE_ROOT,
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome120', 'safari16'],
    external: ['react'],
    define: {
      __PLUGIN_VERSION__: JSON.stringify(VERSION),
    },
    write: false,
    logLevel: 'silent',
    legalComments: 'none',
    sourcemap: false,
    charset: 'utf8',
  })
  if (result.outputFiles.length !== 1) {
    throw new Error(`expected exactly one output file, got ${result.outputFiles.length}`)
  }
  const body = result.outputFiles[0].text.trimEnd()
  const forbidden = /require\(["']@deepseek-ai\//.exec(body)
  if (forbidden !== null) {
    throw new Error(`Client bundle must not require a Harness package: ${forbidden[0]}`)
  }
  return `${BANNER}\n${body}\n${FOOTER}`
}

/**
 * Compare the generated bundle with the committed artifact.
 * @param next - freshly generated text.
 * @returns whether the artifact is current.
 */
async function isCurrent(next) {
  try {
    return (await readFile(OUTPUT, 'utf8')) === next
  } catch {
    return false
  }
}

const next = await bundle()
if (CHECK) {
  if (!(await isCurrent(next))) {
    console.error('client.js is out of date. Run `npm run build` and commit the result.')
    process.exit(1)
  }
  console.log('client.js is up to date')
} else {
  await writeFile(OUTPUT, next, 'utf8')
  console.log(`wrote client.js (${Buffer.byteLength(next, 'utf8')} bytes)`)
}
